print("Análisis estadístico de datos")
datos = [10, 20, 30, 40, 50]

print("Datos:", datos)

suma = sum(datos)
print("Suma:", suma)

promedio = suma / len(datos)
print("Promedio:", promedio)

cantidad = len(datos)
print("Cantidad de elementos:", cantidad)

print("\n--- Resultados del análisis ---")

maximo = max(datos)
print("Máximo:", maximo)

minimo = min(datos)
print("Mínimo:", minimo)

rango = maximo - minimo
print("Rango:", rango)